#!/usr/bin/env node
/**
 * Writes `tests/differential/corpus/<family>/<case>.jsonl` from `corpus-definitions.mjs`.
 *
 *   node scripts/mcp/differential/write-corpus.mjs           # write
 *   node scripts/mcp/differential/write-corpus.mjs --check   # fail when the files are stale
 *
 * Also checks that every case belongs to a family named in `tests/differential/manifest.json`.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildCorpus } from './corpus-definitions.mjs';
import { loadManifest } from './manifest.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const corpusRoot = path.join(repoRoot, 'tests', 'differential', 'corpus');

export function renderCase(definition) {
  const lines = [
    `# generated by scripts/mcp/differential/write-corpus.mjs from corpus-definitions.mjs; edit the definition, not this file`,
    JSON.stringify(definition.header),
    ...definition.steps.map((step) => JSON.stringify(step)),
  ];
  return `${lines.join('\n')}\n`;
}

export function renderCorpus() {
  const files = new Map();
  const manifest = loadManifest(repoRoot);
  for (const definition of buildCorpus()) {
    if (!manifest.families[definition.family]) throw new Error(`case ${definition.name} names unknown family ${definition.family}`);
    const target = path.join(corpusRoot, definition.family, `${definition.name}.jsonl`);
    if (files.has(target)) throw new Error(`two cases write ${target}`);
    files.set(target, renderCase(definition));
  }
  return files;
}

function main() {
  const files = renderCorpus();
  if (process.argv.includes('--check')) {
    const stale = [];
    for (const [file, text] of files) if (!existsSync(file) || readFileSync(file, 'utf8') !== text) stale.push(path.relative(repoRoot, file));
    if (existsSync(corpusRoot)) {
      for (const family of readdirSync(corpusRoot)) {
        for (const file of readdirSync(path.join(corpusRoot, family))) {
          const full = path.join(corpusRoot, family, file);
          if (!files.has(full)) stale.push(`${path.relative(repoRoot, full)} (no definition)`);
        }
      }
    }
    if (stale.length > 0) {
      console.error(`corpus is stale; run node scripts/mcp/differential/write-corpus.mjs\n  ${stale.slice(0, 10).join('\n  ')}`);
      process.exit(1);
    }
    console.log(`corpus current: ${files.size} cases`);
    return;
  }
  rmSync(corpusRoot, { recursive: true, force: true });
  for (const [file, text] of files) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`wrote ${files.size} cases`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
