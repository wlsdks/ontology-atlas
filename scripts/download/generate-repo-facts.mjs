#!/usr/bin/env node
/**
 * Records the repository's public star and fork counts with the day they were read, so
 * `/download` shows a dated number while neither the page nor the build asks GitHub anything.
 * A person runs it; the committed module is the only copy the site reads.
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUTPUT_PATH = path.join(ROOT, "src", "views", "download", "model", "repo-facts.generated.ts");
const REPOSITORY = "wlsdks/ontology-atlas";

function fail(message) {
  console.error(`[download-repo-facts] ${message}`);
  process.exit(1);
}

function count(value, label) {
  if (!Number.isSafeInteger(value) || value < 0) fail(`GitHub returned no usable ${label}: ${JSON.stringify(value)}`);
  return value;
}

if (process.argv.slice(2).some((arg) => arg === "--help" || arg === "-h")) {
  console.log(
    "Usage: pnpm download:repo-facts\n\n" +
      `Reads ${REPOSITORY}'s star and fork counts through the gh CLI and writes them, with\n` +
      "today's UTC date, to src/views/download/model/repo-facts.generated.ts.\n",
  );
  process.exit(0);
}

let repository;
try {
  repository = JSON.parse(
    execFileSync("gh", ["api", `repos/${REPOSITORY}`], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 }),
  );
} catch (error) {
  const stderr = typeof error.stderr === "string" ? error.stderr.trim() : "";
  fail(`gh api repos/${REPOSITORY} failed${stderr ? `: ${stderr}` : ""}`);
}

const stars = count(repository.stargazers_count, "star count");
const forks = count(repository.forks_count, "fork count");
const readOn = new Date().toISOString().slice(0, 10);

fs.writeFileSync(
  OUTPUT_PATH,
  `// Generated by \`pnpm download:repo-facts\` — do not edit by hand.
//
// A count read from GitHub on the day below. The page prints that day beside the numbers and
// never asks GitHub itself, so the figures are as old as this file.

export const REPO_FACTS = {
  stars: ${stars},
  forks: ${forks},
  readOn: '${readOn}',
} as const;
`,
);
console.log(`[download-repo-facts] ${stars} stars, ${forks} forks on ${readOn} → ${path.relative(ROOT, OUTPUT_PATH)}`);
