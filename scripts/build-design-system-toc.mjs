#!/usr/bin/env node
/**
 * `docs/DESIGN-SYSTEM.md` 의 목차를 **헤딩에서 생성**하고, `--check` 로 커밋된
 * 것과 대조한다.
 *
 * ## 왜 손으로 안 쓰나
 *
 * 이 문서는 254KB · 23개 절이고, **인바운드 참조 151개 중 절을 가리키는 것은
 * 0개**였다(2026-08-05 실측) — 전부 「DESIGN-SYSTEM.md 참조」라고만 적혀 있어서,
 * 읽는 쪽은 어디를 봐야 할지 모른 채 통째로 열거나(≈6만 토큰) 포기했다.
 *
 * 목차를 손으로 쓰면 절을 하나 더할 때마다 어긋나고, 그 어긋남은 아무 신호도
 * 내지 않는다. `documentation.md` 의 계약이 허용하는 검사 갈래는 셋뿐이고 그중
 * 하나가 **«생성한 뒤 대조»** 다 — `docs:surface:check` 가 MCP 표면에 쓰는 바로
 * 그 방식이다. 사람이 쓴 문장은 하나도 고정하지 않는다: 이 스크립트가 읽는 것은
 * `## ` 헤딩 텍스트뿐이고, 본문을 아무리 고쳐 써도 목차는 안 깨진다.
 *
 * ## 왜 파일을 쪼개지 않았나
 *
 * 쪼개는 것도 검토했고 반려했다(`docs/DECISIONS.md` 2026-08-05). 이 문서는
 * **docs-vault 노드**라 23개로 쪼개면 앱의 `/docs` 목록에 23개가 생긴다 —
 * 문서 정리가 아니라 제품 표면 변경이다. 게다가 이 저장소에서 더 큰 문서 둘
 * (`CHANGELOG.md` 8,100줄 · `DECISIONS.md` 7,300줄)은 쪼개지 않고도 잘 굴러간다.
 * 그것들이 굴러가는 방식이 **grep 먼저**이고, 목차는 그 grep 에 줄 단어를 준다.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const DOC = path.join(process.cwd(), 'docs/DESIGN-SYSTEM.md');
const START = '<!-- toc:start — generated by scripts/build-design-system-toc.mjs; do not hand-edit -->';
const END = '<!-- toc:end -->';

/** GitHub-style anchor slug (kept simple: this repo's headings are ASCII+Hangul). */
function slug(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[`*_~]/g, '')
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s+/g, '-');
}

export function buildToc(source) {
  const lines = source.split('\n');
  const rows = [];
  let inFence = false;
  lines.forEach((line, i) => {
    if (/^\s*```/.test(line)) inFence = !inFence;
    if (inFence) return;
    const m = /^## (?!#)(.+)$/.exec(line);
    if (!m) return;
    const title = m[1].trim();
    rows.push({ title, line: i + 1, anchor: slug(title) });
  });
  const body = rows
    .map((r) => `- [${r.title}](#${r.anchor})`)
    .join('\n');
  return { rows, block: `${START}\n\n${body}\n\n${END}` };
}

export function render(source) {
  const { block, rows } = buildToc(source);
  const s = source.indexOf(START);
  const e = source.indexOf(END);
  if (s !== -1 && e !== -1) {
    return { next: source.slice(0, s) + block + source.slice(e + END.length), rows };
  }
  // first insertion: after the frontmatter + H1 + intro blockquote, before the first `## `
  const firstSection = source.search(/^## /m);
  if (firstSection === -1) throw new Error('DESIGN-SYSTEM.md 에 `## ` 절이 하나도 없다');
  return { next: `${source.slice(0, firstSection)}${block}\n\n${source.slice(firstSection)}`, rows };
}

const check = process.argv.includes('--check');
const source = readFileSync(DOC, 'utf8');
const { next, rows } = render(source);

if (check) {
  if (next !== source) {
    console.error('[design-toc] 목차가 헤딩과 어긋난다 — `pnpm design:toc` 로 다시 생성하라.');
    process.exit(1);
  }
  console.log(`[design-toc] current · ${rows.length} sections`);
} else {
  writeFileSync(DOC, next);
  console.log(`[design-toc] wrote ${rows.length} sections → docs/DESIGN-SYSTEM.md`);
}
