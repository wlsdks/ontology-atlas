#!/usr/bin/env node
/**
 * Generates the table of contents of `docs/DESIGN-SYSTEM.md` from its headings; `--check` compares
 * it with the committed one. Only `## ` heading text is read, so no prose is pinned. The file
 * stays unsplit: it is a docs-vault node, so splitting adds `/docs` entries.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { headingAnchorSlug } from './lib/doc-links.mjs';

const DOC = path.join(process.cwd(), 'docs/DESIGN-SYSTEM.md');
const START = '<!-- toc:start — generated by scripts/build-design-system-toc.mjs; do not hand-edit -->';
const END = '<!-- toc:end -->';

/**
 * One slug function, shared with the link gate: `headingAnchorSlug` in
 * `scripts/lib/doc-links.mjs`, verified against GitHub's rendered ids. The local
 * copy this replaces collapsed runs of whitespace and dropped `_`, so every
 * heading holding an em dash or a snake_case token produced a table-of-contents
 * link that resolved nowhere — 13 of them in this document, unnoticed because
 * nothing checked the part after the `#`.
 */

export function buildToc(source) {
  const lines = source.split('\n');
  const rows = [];
  let inFence = false;
  lines.forEach((line, i) => {
    if (/^\s*```/.test(line)) inFence = !inFence;
    if (inFence) return;
    const m = /^## (?!#)(.+)$/.exec(line);
    if (!m) return;
    const title = m[1].trim();
    rows.push({ title, line: i + 1, anchor: headingAnchorSlug(title) });
  });
  const body = rows
    .map((r) => `- [${r.title}](#${r.anchor})`)
    .join('\n');
  return { rows, block: `${START}\n\n${body}\n\n${END}` };
}

export function render(source) {
  const { block, rows } = buildToc(source);
  const s = source.indexOf(START);
  const e = source.indexOf(END);
  if (s !== -1 && e !== -1) {
    return { next: source.slice(0, s) + block + source.slice(e + END.length), rows };
  }
  // first insertion: after the frontmatter + H1 + intro blockquote, before the first `## `
  const firstSection = source.search(/^## /m);
  if (firstSection === -1) throw new Error('DESIGN-SYSTEM.md has no `## ` section at all');
  return { next: `${source.slice(0, firstSection)}${block}\n\n${source.slice(firstSection)}`, rows };
}

const check = process.argv.includes('--check');
const source = readFileSync(DOC, 'utf8');
const { next, rows } = render(source);

if (check) {
  if (next !== source) {
    console.error('[design-toc] the table of contents disagrees with the headings — run `pnpm design:toc` to regenerate it.');
    process.exit(1);
  }
  console.log(`[design-toc] current · ${rows.length} sections`);
} else {
  writeFileSync(DOC, next);
  console.log(`[design-toc] wrote ${rows.length} sections → docs/DESIGN-SYSTEM.md`);
}
