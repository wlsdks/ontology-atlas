#!/usr/bin/env node
/**
 * Generates the **specimen** the download page's conduction figure casts: one real capability
 * node of this repository's vault, its first dependency and the code path it names.
 *
 * ## Why this is generated and not written by hand
 *
 * The figure claims an agent reads this exact node. A hand-typed copy of its ids stops being true
 * the moment someone edits the vault, and nothing would say so. So the rule this follows is the
 * repository's own (`.claude/rules/documentation.md`): **only what a machine can generate may be
 * checked**, and the way to check it is to generate it again and diff. `--check` does that.
 *
 * `SPECIMEN_SLUG` pins which node. It is pinned rather than picked heuristically because the
 * figure's prose explains this exact node; a specimen that silently changed under a fixed
 * explanation would be drift in a new place.
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import { listLocales } from './build-messages.mjs';

const ROOT = process.cwd();
const VAULT = path.join(ROOT, 'docs', 'ontology');
const OUT = path.join(ROOT, 'src', 'views', 'download', 'model', 'evidence-specimen.generated.ts');

/** The pinned specimen. Changing this is a content decision, not a refactor. */
const SPECIMEN_SLUG = 'capabilities/mcp-tool-server';

function readFrontmatter(file) {
  const text = fs.readFileSync(file, 'utf8');
  const match = /^---\n([\s\S]*?)\n---/.exec(text);
  if (!match) throw new Error(`${file}: has no frontmatter`);
  return match[1].split('\n');
}

/** `key: value` from a frontmatter line list; returns null when the key is absent. */
function field(lines, key) {
  const hit = lines.find((line) => line.startsWith(`${key}:`));
  return hit ? hit.slice(key.length + 1).trim() : null;
}

function unquote(value) {
  return value?.replace(/^["']|["']$/g, '') ?? null;
}

/**
 * Names plus the **map node id** for a slug. The id is `kind:basename`, the form
 * `derivationToInsight` mints (`domain:payment`).
 */
function namesFor(slug, locales) {
  const lines = readFrontmatter(path.join(VAULT, `${slug}.md`));
  const title = unquote(field(lines, 'title')) ?? slug;
  const kind = unquote(field(lines, 'kind')) ?? 'capability';
  const names = Object.fromEntries(locales.map((l) => [l, unquote(field(lines, `display_${l}`)) ?? title]));
  return { ...names, nodeId: `${kind}:${slug.split('/').pop()}` };
}

function orderLocales(locales) {
  const rest = locales.filter((l) => l !== 'ko' && l !== 'en');
  return ['ko', 'en'].filter((l) => locales.includes(l)).concat(rest);
}

export function build(localeList = listLocales()) {
  const locales = orderLocales(localeList);
  const lines = readFrontmatter(path.join(VAULT, `${SPECIMEN_SLUG}.md`));

  const depsRaw = field(lines, 'dependencies') ?? '[]';
  const depSlug = depsRaw.replace(/[[\]]/g, '').split(',')[0]?.trim() || null;
  const dependency = depSlug ? namesFor(depSlug, locales) : null;
  const implPath = unquote(field(lines, 'path'));

  if (!dependency || !implPath) {
    throw new Error(
      `${SPECIMEN_SLUG}: the specimen must carry dependencies and path together ` +
        `(dependencies=${!!dependency} path=${!!implPath})`,
    );
  }

  return {
    slug: SPECIMEN_SLUG,
    facts: {
      name: namesFor(SPECIMEN_SLUG, locales),
      dependency,
      implPath,
    },
  };
}

function render(spec) {
  const json = JSON.stringify(spec, null, 2).replace(/^/gm, '  ').trim();
  return `// Generated by \`pnpm gateway:specimen\` — do not edit by hand.
//
// One real node of this repository's own vault, the one the download page's conduction figure
// casts. Re-run the generator when the node changes; \`pnpm gateway:specimen:check\` fails the
// build when this file and the vault disagree. Rationale: \`scripts/generate-evidence-specimen.mjs\`.

interface EvidenceSpecimenName {
  readonly en: string;
  readonly [locale: string]: string;
  /** The map engine's node id (kind:basename). */
  readonly nodeId: string;
}

export interface EvidenceSpecimen {
  /** Vault-relative slug — the string MCP and the CLI accept verbatim. */
  readonly slug: string;
  readonly facts: {
    readonly name: EvidenceSpecimenName;
    readonly dependency: EvidenceSpecimenName;
    readonly implPath: string;
  };
}

export const EVIDENCE_SPECIMEN: EvidenceSpecimen = ${json} as const;
`;
}

function main() {
  const spec = build();
  const next = render(spec);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== next) {
      console.error(
        '[gateway:specimen] the generated file disagrees with the vault — run `pnpm gateway:specimen` and commit the result.',
      );
      process.exit(1);
    }
    console.log(`[gateway:specimen] current · ${spec.slug}`);
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`[gateway:specimen] ${spec.slug} → ${path.relative(ROOT, OUT)}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
