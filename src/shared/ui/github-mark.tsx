import type { SVGProps } from 'react';

/**
 * GitHub 마크(Invertocat) — **플랫폼 지시자**이지 우리 브랜드가 아니다.
 *
 * ## 왜 lucide 가 아니라 인라인 SVG 인가
 *
 * `lucide-react` 는 브랜드 아이콘을 전부 뺐다(실측 2026-07-29:
 * `typeof l.Github === 'undefined'`). 이 앱이 쓰는 유일한 아이콘 세트에 없으므로
 * 마크를 쓰려면 인라인 path 뿐이다. 좌표는 GitHub 자신이 배포하는 Octicons
 * `mark-github-16` 을 **그대로** 옮긴 것이고, 손대지 않는 것이 계약이다 —
 * 로고를 변형하면 그 순간 「그 플랫폼을 가리키는 마크」가 아니라 「우리가 만든
 * 로고 비슷한 것」이 된다.
 *
 * ## 헌장 판정 — 이것은 「타사 자산 모방」이 아니다 (2026-07-29)
 *
 * `forbidden.md` 의 두 조항을 각각 확인했다.
 *
 * - **「다른 서비스 브랜드를 식별자/라벨/주석에 박기」** 는 *우리 것을 남의
 *   이름으로 부르는 것*(`Notion-killer`, 내부 codename)을 막는 조항이다.
 *   여기서 GitHub 은 우리 것의 이름이 아니라 **링크의 목적지**이고, 그 목적지는
 *   실제로 GitHub 이다. 거짓 연상이 없으므로 이 조항의 사정거리 밖이다.
 * - **「타사 자산/비주얼 모방 금지」** 는 *남의 디자인 언어를 우리 화면에
 *   입히는 것*을 막는다. 플랫폼 마크로 그 플랫폼을 가리키는 것은 모방이 아니라
 *   그 마크의 본래 용도이고(GitHub 로고 가이드라인도 저장소로 링크하는 용도를
 *   허용한다), 여기서 우리는 GitHub 의 **레이아웃·색·서체를 하나도 안 가져온다**.
 *   가져온 것은 목적지의 이름표 하나다.
 *
 * 반대로 마크를 **안 쓰는** 쪽이 지불하는 비용이 크다: `↗` 는 "밖으로 나간다"
 * 까지만 말하고 **어디로** 는 말하지 않는데, 오픈소스 제품에서 이 컨트롤의
 * 존재 이유가 정확히 그 "어디로" 다.
 *
 * ## 색 — `currentColor` 단색
 *
 * GitHub 자신이 단색 변형(`github-mark-white.svg`)을 배포하므로 단색화는 변형이
 * 아니라 지원되는 사용이다. 이 앱은 무채색 + 단일 인디고라 마크가 자기 색을
 * 들고 오면 그것이 **세 번째 채색 시스템**이 된다(`design.md` 금지). 호출부의
 * 텍스트 색을 그대로 상속한다.
 *
 * ## 크기 — 기본 14, Octicons 원본은 16
 *
 * 이 마크는 16×16 을 **가장자리까지 채우는 원**이다. 같은 자리에 있던
 * lucide `external-link` 는 24 뷰박스 안에 여백을 두고 그려서 14px 로 렌더해도
 * 실제 시각 지름이 ~12.8px 이었다. 16 을 그대로 쓰면 2차 컨트롤의 아이콘이
 * 주 CTA 의 아이콘보다 무거워진다 — 주목 승자를 흔드는 값이다. 그래서 기본은
 * 광학적으로 앞의 것과 같은 자리를 차지하는 14 다.
 */
const OCTICON_MARK_GITHUB_16 =
  'M8 0c4.42 0 8 3.58 8 8a8.013 8.013 0 0 1-5.45 7.59c-.4.08-.55-.17-.55-.38 0-.27.01-1.13.01-2.2 0-.75-.25-1.23-.54-1.48 1.78-.2 3.65-.88 3.65-3.95 0-.88-.31-1.59-.82-2.15.08-.2.36-1.02-.08-2.12 0 0-.67-.22-2.2.82-.64-.18-1.32-.27-2-.27-.68 0-1.36.09-2 .27-1.53-1.03-2.2-.82-2.2-.82-.44 1.1-.16 1.92-.08 2.12-.51.56-.82 1.28-.82 2.15 0 3.06 1.86 3.75 3.64 3.95-.23.2-.44.55-.51 1.07-.46.21-1.61.55-2.33-.66-.15-.24-.6-.83-1.23-.82-.67.01-.27.38.01.53.34.19.73.9.82 1.13.16.45.68 1.31 2.69.94 0 .67.01 1.3.01 1.49 0 .21-.15.45-.55.38A7.995 7.995 0 0 1 0 8c0-4.42 3.58-8 8-8Z';

export interface GithubMarkProps
  extends Omit<SVGProps<SVGSVGElement>, 'width' | 'height' | 'viewBox' | 'children'> {
  /** 렌더 크기(px), 정사각형. 기본 14 — 위 주석의 광학 보정. */
  size?: number;
}

export function GithubMark({ size = 14, ...rest }: GithubMarkProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill="currentColor"
      // 라벨이 있는 컨트롤 안의 마크라 기본은 장식이다. 목적지 이름을 스크린
      // 리더에도 주고 싶으면 호출부가 `aria-hidden={false}` + `aria-label` 로
      // 덮는다.
      aria-hidden
      focusable="false"
      {...rest}
    >
      <path data-mark-part="octicon" d={OCTICON_MARK_GITHUB_16} />
    </svg>
  );
}
