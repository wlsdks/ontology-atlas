import { LG_BREAKPOINT_PX } from "@/shared/lib/use-viewport-below";

/**
 * 공방 오른쪽 에이전트 도크가 **자리를 요구해도 되는 최소 뷰포트.**
 *
 * ## 왜 지도와 달리 폭 조건이 붙나
 *
 * 지도는 도크가 열리면 캔버스가 좁아질 뿐 계속 성립한다. 공방은 아니다 —
 * 나침 무대는 고정 폭 카드 + 위성 기하라 1024px 미만에서 성립하지 않고, 그래서
 * 라우트에 이미 폭 강등(`StudioTooNarrow`)이 걸려 있다.
 *
 * 그 강등은 **뷰포트** 폭을 본다. 도크는 **무대가 실제로 쓰는** 폭을 줄인다.
 * 둘을 잇지 않으면 1280px 화면에서 도크가 열리는 순간 무대가 947px 로 눌리는데,
 * 강등은 뷰포트가 1280 이라 발화하지 않는다 — **정확히 그 폭 가드가 막으려던
 * 상태에 가드를 통과한 채로 들어간다.**
 *
 * 그래서 임계를 여기서 한 번 유도한다:
 *
 *     무대가 필요한 폭(LG 1024) + 도크가 가져가는 최대 폭(420) = 1444
 *
 * 도크 폭은 `clamp(320px, 26vw, 420px)` 이라 실제로는 대개 420보다 작지만,
 * **상한을 쓰는 것이 보수적인 선택**이고 clamp 를 런타임에 되풀이 계산하지
 * 않아도 된다. 좁은 화면에서는 도크를 아예 안 그린다 — 열 수 있는데 열면
 * 깨지는 문은 문이 아니라 함정이다.
 */
export const STUDIO_AGENT_DOCK_MAX_WIDTH_PX = 420;

export const STUDIO_AGENT_DOCK_MIN_VIEWPORT_PX =
  LG_BREAKPOINT_PX + STUDIO_AGENT_DOCK_MAX_WIDTH_PX;
