/**
 * The repository as units: every source file classed (product, test, example,
 * benchmark, generated, vendored, docs, tooling, migration), and product files grouped into
 * units — a top-level package, workspace member or module folder, split one level
 * further when it is large. The survey lists these units, and the coverage line
 * every write reports is measured against them, so both speak of the same thing.
 * Reads file bytes only to count lines and spot a generated header; nothing runs.
 */

import { lstatSync, readdirSync, readFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';

import { DEFAULT_IGNORE } from '../analysis-limits-and-tables.mjs';
import { discoverDeclaredWorkspacePackages } from '../../infer-imports/workspace-packages.mjs';

export const UNIT_SOURCE_EXTENSIONS = new Set([
  '.c', '.cc', '.cjs', '.cpp', '.cs', '.cts', '.dart', '.ex', '.exs', '.go', '.h', '.hpp',
  '.java', '.js', '.jsx', '.kt', '.kts', '.lua', '.mjs', '.mts', '.php', '.py', '.rb', '.rs',
  '.scala', '.svelte', '.swift', '.ts', '.tsx', '.vue', '.zig',
]);

/** A folder whose children are the units, never a unit itself. */
const CONTAINER_FOLDERS = new Set([
  'apps', 'cmd', 'crates', 'internal', 'lib', 'libs', 'modules', 'packages', 'pkg', 'plugins',
  'source', 'src',
]);

/** A unit holding more product files than this is split into its subfolders. */
const UNIT_SPLIT_FILES = 25;

/** A file this long in a split folder is a module of its own (not Go: a Go folder is one package). */
const MODULE_UNIT_LINES = 300;

const MAX_FILES = 8000;
const MAX_FILE_BYTES = 1024 * 1024;
const SENSITIVE = /^(?:credential|credentials|secret|secrets|private[-_]?key|id_rsa|id_ed25519)(?:\.[^.]+)?$/i;

const VENDORED = new Set(['vendor', 'vendored', 'vendorlib', 'third_party', 'third-party', 'thirdparty']);
const TESTS = new Set([
  '__fixtures__', '__mocks__', '__tests__', 'e2e', 'fixtures', 'mock', 'mocks', 'node_mocks', 'spec',
  'specs', 'test', 'testdata', 'tests',
]);
const BENCHMARKS = new Set(['bench', 'benches', 'benchmark', 'benchmarks', 'gobench']);
const EXAMPLES = new Set(['demo', 'demos', 'example', 'examples', 'playground', 'sample', 'samples']);
const DOCS = new Set(['doc', 'docs', 'documentation', 'site', 'website']);
const TOOLING = new Set(['ci', 'etc', 'hack', 'packaging', 'script', 'scripts', 'tool', 'tools']);
const ROOT_TOOLING_FILE = /\.config\.[cm]?[jt]s$|^(?:setup|noxfile|tasks|fabfile|conftest|manage|print_system)\.py$|^(?:gulpfile|gruntfile|webpack|rollup|vite|vitest|jest|babel|eslint|prettier)\b/i;
const TEST_FILE = /(?:^test_.+\.py$|_test\.(?:go|py)$|\.(?:test|spec)\.[cm]?[jt]sx?$|_spec\.rb$|^conftest\.py$)/i;
const BENCH_FILE = /(?:_bench\.|^bench_|\.bench\.)/i;
const GENERATED_FILE = /(?:\.pb\.\w+$|_pb2(?:_grpc)?\.py$|\.gen\.\w+$|_gen\.go$|_generated\.\w+$|^zz_generated|\.min\.js$)/i;
const GENERATED_HEADER = /Code generated .{0,80}DO NOT EDIT|@generated|auto-generated|autogenerated|This file was automatically generated/i;
/** Schema history: numbered or timestamp-prefixed files (`0001_initial.py`, `20240101120000_add_users.rb`). */
const MIGRATION_FOLDERS = new Set(['migrate', 'migration', 'migrations', 'versions']);
const MIGRATION_FILE = /^\d{3,}(?:[_-]|\.[a-z]+$)/i;

function countLines(text) {
  if (text.length === 0) return 0;
  let lines = 0;
  for (let index = text.indexOf('\n'); index !== -1; index = text.indexOf('\n', index + 1)) lines += 1;
  return text.endsWith('\n') ? lines : lines + 1;
}

/** One file's class from its path alone, or from its first bytes when the name is silent. */
function classOf(path, head) {
  const parts = path.split('/');
  const dirs = parts.slice(0, -1).map((part) => part.toLowerCase());
  const name = parts.at(-1);
  if (dirs.some((directory) => VENDORED.has(directory))) return 'vendored';
  if (GENERATED_FILE.test(name) || GENERATED_HEADER.test(head)) return 'generated';
  if (dirs.some((directory) => TESTS.has(directory)) || TEST_FILE.test(name)) return 'test';
  if (MIGRATION_FOLDERS.has(dirs.at(-1)) && MIGRATION_FILE.test(name)) return 'migration';
  if (dirs.some((directory) => BENCHMARKS.has(directory)) || BENCH_FILE.test(name)) return 'benchmark';
  if (dirs.some((directory) => EXAMPLES.has(directory))) return 'example';
  if (dirs.length > 0 && DOCS.has(dirs[0])) return 'docs';
  if (dirs.length > 0 && TOOLING.has(dirs[0])) return 'tooling';
  if (dirs.length === 0 && ROOT_TOOLING_FILE.test(name)) return 'tooling';
  return 'product';
}

function walkSourceFiles(rootPath, ignore, excludedPrefixes) {
  const out = [];
  const visit = (directory) => {
    if (out.length >= MAX_FILES) return;
    let names;
    try { names = readdirSync(directory).sort(); } catch { return; }
    for (const name of names) {
      if (out.length >= MAX_FILES) return;
      if (name.startsWith('.') || ignore.has(name) || SENSITIVE.test(name)) continue;
      const abs = join(directory, name);
      const rel = relative(rootPath, abs).split(sep).join('/');
      if (excludedPrefixes.some((prefix) => rel === prefix || rel.startsWith(`${prefix}/`))) continue;
      let stat;
      // lstat: a link is neither a file nor a folder here, so the walk never follows one.
      try { stat = lstatSync(abs); } catch { continue; }
      if (stat.isDirectory()) visit(abs);
      else if (stat.isFile() && UNIT_SOURCE_EXTENSIONS.has(extname(name).toLowerCase())) {
        out.push({ abs, path: rel, size: stat.size, mtimeMs: stat.mtimeMs });
      }
    }
  };
  visit(rootPath);
  return { files: out, truncated: out.length >= MAX_FILES };
}

/*
 * Lines and class per file, keyed by path, size and mtime, so the coverage line on
 * every write re-reads only what changed since the last call.
 */
const FILE_FACTS = new Map();

function factsFor(file) {
  const key = `${file.abs}\0${file.size}\0${file.mtimeMs}`;
  const cached = FILE_FACTS.get(key);
  if (cached) return cached;
  let facts;
  if (file.size > MAX_FILE_BYTES) {
    facts = { lines: 0, class: 'generated' };
  } else {
    let text = '';
    try { text = readFileSync(file.abs, 'utf8'); } catch { text = ''; }
    facts = { lines: countLines(text), class: classOf(file.path, text.slice(0, 1024)) };
  }
  if (FILE_FACTS.size > 20000) FILE_FACTS.clear();
  FILE_FACTS.set(key, facts);
  return facts;
}

function workspaceMembers(rootPath, ignore) {
  try {
    return discoverDeclaredWorkspacePackages(rootPath, { ignore }).packages
      .filter((row) => typeof row.path === 'string' && row.path && row.path !== '.')
      .map((row) => ({ path: row.path.split(sep).join('/'), name: row.name }));
  } catch {
    return [];
  }
}

/** Files as nested folders, each with `total` files and `lines` beneath it; O(files x depth). */
export function folderTree(files) {
  const folder = (path) => ({ path, files: [], children: new Map(), total: 0, lines: 0 });
  const root = folder('');
  for (const file of files) {
    const parts = file.path.split('/');
    let node = root;
    node.total += 1;
    node.lines += file.lines;
    for (const part of parts.slice(0, -1)) {
      if (!node.children.has(part)) node.children.set(part, folder(node.path ? `${node.path}/${part}` : part));
      node = node.children.get(part);
      node.total += 1;
      node.lines += file.lines;
    }
    node.files.push(file);
  }
  return root;
}

function treeFiles(node) {
  return [...node.files, ...[...node.children.values()].flatMap(treeFiles)];
}

/**
 * Product files into units. A container folder (`src`, `packages`, `plugins` …) or
 * a folder over the split size hands its subfolders on as units; its own files form
 * one unit, except a long file outside a Go package, which is a module of its own.
 */
function groupUnits(productFiles, members) {
  const memberPaths = new Set(members.map((member) => member.path));
  const units = [];
  const push = (path, scope, files) => {
    if (files.length === 0) return;
    units.push({ path: path || '.', scope, files });
  };
  const unitize = (node, forceSplit) => {
    if (node.total === 0) return;
    const name = node.path.split('/').at(-1) ?? '';
    const isMember = memberPaths.has(node.path);
    const files = treeFiles(node);
    const goPackage = files.every((file) => extname(file.path) === '.go');
    const split = forceSplit
      || (!isMember && CONTAINER_FOLDERS.has(name.toLowerCase()))
      || (node.total > UNIT_SPLIT_FILES && node.children.size > 0)
      // A folder that holds workspace members never becomes one unit over them.
      || [...memberPaths].some((member) => member.startsWith(`${node.path}/`));
    if (!split) {
      push(node.path, 'tree', files);
      return;
    }
    const loose = [];
    for (const file of node.files) {
      if (!goPackage && file.lines >= MODULE_UNIT_LINES && node.files.length > 1) {
        push(file.path, 'file', [file]);
      } else {
        loose.push(file);
      }
    }
    push(node.path, 'files', loose);
    for (const child of node.children.values()) unitize(child, false);
  };
  unitize(folderTree(productFiles), true);
  return units;
}

function vaultExclusion(rootPath, vaultRoot) {
  if (!vaultRoot) return [];
  const rel = relative(rootPath, vaultRoot).split(sep).join('/');
  if (!rel || rel === '.' || rel.startsWith('..')) return [];
  return [rel];
}

/**
 * Every source file with its class and line count, and the product units.
 *
 * @param {string} rootPath absolute repository root
 * @param {{ ignore?: string[], vaultRoot?: string }} [options]
 */
export function collectSourceUnits(rootPath, { ignore = [], vaultRoot } = {}) {
  const ignoreSet = new Set([...DEFAULT_IGNORE, ...ignore]);
  const { files, truncated } = walkSourceFiles(rootPath, ignoreSet, vaultExclusion(rootPath, vaultRoot));
  const classed = files.map((file) => ({ ...file, ...factsFor(file) }));
  const product = classed.filter((file) => file.class === 'product' && file.lines > 0);
  const members = workspaceMembers(rootPath, ignoreSet);
  const units = groupUnits(product, members)
    .map((unit) => ({
      ...unit,
      lines: unit.files.reduce((sum, file) => sum + file.lines, 0),
    }))
    .sort((a, b) => a.path.localeCompare(b.path));
  const unitOfFile = new Map();
  for (const unit of units) for (const file of unit.files) unitOfFile.set(file.path, unit);
  const excluded = new Map();
  for (const file of classed) {
    if (file.class === 'product') continue;
    const top = file.path.includes('/') ? file.path.split('/')[0] : '.';
    const key = `${file.class}\0${top}`;
    const row = excluded.get(key) ?? { path: top, class: file.class, files: 0, lines: 0 };
    row.files += 1;
    row.lines += file.lines;
    excluded.set(key, row);
  }
  return {
    rootPath,
    files: classed,
    units,
    unitOfFile,
    members,
    excluded: [...excluded.values()].sort((a, b) => b.lines - a.lines),
    productFiles: product.length,
    productLines: product.reduce((sum, file) => sum + file.lines, 0),
    truncated,
  };
}

/** The unit a repository-relative `path:` lands in: a file's own unit, or a unit named exactly. */
export function unitForPath(collection, rawPath) {
  const path = String(rawPath ?? '').trim().replace(/^\.\//, '').replace(/\/+$/, '');
  if (!path) return null;
  const byFile = collection.unitOfFile.get(path);
  if (byFile) return byFile;
  return collection.units.find((unit) => unit.path === path) ?? null;
}
