/**
 * Does this title look like a file path rather than a concept name? The code
 * half of the naming rule, firing whatever the model read. Deliberately narrow (a
 * slash or a source extension, and no internal whitespace, since prose titles
 * contain slashes too): a warning that cries wolf gets filtered out.
 */
export function looksLikePath(title) {
  if (typeof title !== "string") return false;
  const t = title.trim();
  if (t.length === 0) return false;
  if (/\s/.test(t)) return false;
  if (t.includes("/") || t.includes("\\")) return true;
  return /\.(m?[jt]sx?|py|rb|go|rs|java|kt|swift|c|cc|cpp|h|hpp|css|scss|json|ya?ml|toml|sh)$/i.test(t);
}

/**
 * Slugs are slash-separated too, so {@link looksLikePath} cannot tell a file from
 * a slug reference. A reference starting in a kind folder the schema creates
 * claims to be a node; anything else path-shaped claims to be a file.
 */
const VAULT_FOLDER_SEGMENTS = new Set(
  Object.values(VAULT_KIND_SCHEMA)
    .map((schema) => schema.folder)
    .filter(Boolean)
    .map((folder) => folder.replace(/\/$/, '')),
);

/**
 * Is this graph-array entry evidence (a file) rather than a node reference? Never
 * decides a defect: callers ask only about entries that already failed to
 * resolve, and the answer only picks which repair the message names first, so a
 * heuristic is acceptable.
 */
export function looksLikeEvidencePath(ref) {
  if (!looksLikePath(ref)) return false;
  const trimmed = String(ref).trim();
  if (trimmed.includes('\\')) return true;
  const segments = trimmed.split('/');
  if (segments.length === 1) return true; // bare "absorb.mjs" — the extension clause fired
  return !VAULT_FOLDER_SEGMENTS.has(segments[0]);
}

/** Warning literal for {@link looksLikePath}. Advisory — never blocks the write. */
export function pathShapedTitleMessage(title) {
  return `title "${title}" looks like a file path, not a concept name — elements name a role, not a location. If this file plays a distinct role, rename the title to that role and move the path into path:. If it doesn't, patch_concept the parent capability's body instead of adding another file-mirror node.`;
}

/**
 * Action text for a dense parent whose references are mostly broken. It proposes
 * a question, then a call, never a ready-made split (the shortest path to empty
 * buckets), and keeps a "leave it alone" exit so the number never becomes the
 * goal. The test that holds: one non-circular sentence on why a child is not
 * interchangeable with its siblings. `basis` keeps a bootstrap trigger from being
 * printed as the vault's own p90; a shared prefix is only a hint.
 *
 * @param {object} args
 * @param {string} args.parentSlug
 * @param {number} args.count resolved children; unresolved strings are not children
 * @param {string} args.childKind
 * @param {number} args.trigger the number crossed, whatever its basis
 * @param {'vault-p90'|'bootstrap'} args.basis where `trigger` came from
 * @param {string} args.evidence why this parent was looked at
 */
export function denseParentActionMessage({ parentSlug, count, childKind, trigger, basis, evidence }) {
  const source = basis === 'vault-p90'
    ? `this vault's own p90 for ${childKind} parents is ${trigger}`
    : `the starting range for ${childKind} children is ${trigger} (this vault has too few ${childKind} parents yet for its own percentile to mean anything)`;
  return `"${parentSlug}" has ${count} ${childKind} children that resolve to real nodes, and ${source}. That number is a trigger, not a limit — nothing here caps how many children a node may have, and a wide parent whose children each earn their place is correct. What made this worth mentioning is ${evidence}. Call get_concepts({slugs:["${parentSlug}"]}) and answer one question per child: can you write a non-circular sentence saying why it is NOT interchangeable with its siblings? For every child where you can, leave it alone. Where you cannot for three or more, those children want a BRIDGE NODE — one node named after the behavior they share, with them reparented onto it; the construction rules list the four conditions a bridge has to meet, and a bridge you leave empty is reported back to you for retirement. Shared name prefixes are a hint worth glancing at, not the test — in this vault, prefixed siblings have been legitimate and the broken ones shared no prefix at all.`;
}

/** The count plus a few examples: pasting every ref is unread by a person and costs an agent context. */
function sampleRefs(refs, limit) {
  const shown = refs.slice(0, limit).map((ref) => `"${ref}"`).join(', ');
  const rest = refs.length - Math.min(refs.length, limit);
  return rest > 0 ? `${shown} and ${rest} more` : shown;
}

/**
 * Warning literal for an entry a kind change could not move: the referrer's kind
 * keeps no list for the new kind (spec §5), so the entry stays, still resolves,
 * and fires no compile warning. Only the writer knows, so the writer says it.
 */
export function containmentEntryKeptMessage({ slug, key, ref, holderKind, newKind }) {
  const holder = holderKind ? `a ${holderKind}` : 'a document with no kind';
  return `"${slug}" still lists "${ref}" under ${key}:, but "${ref}" is now a ${newKind} and ${holder} keeps no list for a ${newKind}, so the entry was left where it was rather than guessed into another relation. Readers still count it as one of "${slug}"'s ${key}. Decide what "${slug}" means by it: remove_relation({from:"${slug}", to:"${ref}", type:"${key}"}) drops it, and an add_relations row with the type that fits restates it.`;
}

/**
 * Warning literal for a graph-array entry that resolves to no node. It names both
 * exits and carries no `proposedAction`: a literal "create the node" makes an
 * agent manufacture one node per unresolved string.
 */
export function danglingGraphReferenceMessage({ slug, key, refs, count, sampleLimit }) {
  return `${count} entry/entries in "${slug}".${key} resolve to no vault node: ${sampleRefs(refs, sampleLimit)}. A relation array is a claim that a node exists; an unresolved string is not a child, it is a name with nothing behind it. Either promote it — add_concepts({concepts:[{slug, kind, title}]}) for the concept it names, then keep the reference — or drop it from ${key}: and record what it points at as evidence on this node instead. Do not leave it in a meaning slot.`;
}

/**
 * Warning literal for a file path in a graph-relation array. validate_vault
 * exempts path-shaped `elements:` entries (`isPathLikeGraphRef`) and the
 * compiler only prescribes "create a node per file", so only the write path can
 * say "this does not belong here".
 */
export function pathShapedReferenceMessage({ slug, key, refs, count, sampleLimit }) {
  return `${count} entry/entries in "${slug}".${key} are file paths, not concept names: ${sampleRefs(refs, sampleLimit)}. A path is EVIDENCE for a concept, not the concept — it names where something lives, so it cannot be a child in the graph. For each one, either write the sentence that says what distinct role that file plays and promote it with add_concepts({concepts:[{kind:"element", title:"<the role>", path:"<the path>"}]}), or remove it from ${key}: and keep the path as evidence on "${slug}" (frontmatter path: / the node body). One node per file, mirroring a directory listing, is the failure this check exists to stop.`;
}

