//! What kind of file a source file is: the product itself, or what stands beside it. The survey
//! counts the product apart, and says how much it left out of each other kind.

use std::sync::LazyLock;

use regex::Regex;

use crate::js_pattern::js_regex;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SourceClass {
    Product,
    Test,
    Example,
    Benchmark,
    Generated,
    Vendored,
    Docs,
    Tooling,
    Migration,
}

impl SourceClass {
    pub fn word(self) -> &'static str {
        match self {
            Self::Product => "product",
            Self::Test => "test",
            Self::Example => "example",
            Self::Benchmark => "benchmark",
            Self::Generated => "generated",
            Self::Vendored => "vendored",
            Self::Docs => "docs",
            Self::Tooling => "tooling",
            Self::Migration => "migration",
        }
    }
}

const VENDORED: [&str; 6] = [
    "vendor",
    "vendored",
    "vendorlib",
    "third_party",
    "third-party",
    "thirdparty",
];
const TESTS: [&str; 11] = [
    "__fixtures__",
    "__mocks__",
    "__tests__",
    "e2e",
    "fixtures",
    "mock",
    "mocks",
    "node_mocks",
    "spec",
    "specs",
    "test",
];
const MORE_TESTS: [&str; 2] = ["testdata", "tests"];
const BENCHMARKS: [&str; 5] = ["bench", "benches", "benchmark", "benchmarks", "gobench"];
const EXAMPLES: [&str; 7] = [
    "demo",
    "demos",
    "example",
    "examples",
    "playground",
    "sample",
    "samples",
];
const DOCS: [&str; 5] = ["doc", "docs", "documentation", "site", "website"];
const TOOLING: [&str; 8] = [
    "ci",
    "etc",
    "hack",
    "packaging",
    "script",
    "scripts",
    "tool",
    "tools",
];
const MIGRATION_FOLDERS: [&str; 4] = ["migrate", "migration", "migrations", "versions"];

static ROOT_TOOLING_CONFIG: LazyLock<Regex> = LazyLock::new(|| {
    js_regex(
        r"(?i)\.config\.[cm]?[jt]s$|^(?:setup|noxfile|tasks|fabfile|conftest|manage|print_system)\.py$|^(?:gulpfile|gruntfile|webpack|rollup|vite|vitest|jest|babel|eslint|prettier)\b",
    )
});
static TEST_FILE: LazyLock<Regex> = LazyLock::new(|| {
    js_regex(
        r"(?i)(?:^test_[^\n\r\x{2028}\x{2029}]+\.py$|_test\.(?:go|py)$|\.(?:test|spec)\.[cm]?[jt]sx?$|_spec\.rb$|^conftest\.py$)",
    )
});
static BENCH_FILE: LazyLock<Regex> =
    LazyLock::new(|| js_regex(r"(?i)(?:_bench\.|^bench_|\.bench\.)"));
static GENERATED_FILE: LazyLock<Regex> = LazyLock::new(|| {
    js_regex(
        r"(?i)(?:\.pb\.\w+$|_pb2(?:_grpc)?\.py$|\.gen\.\w+$|_gen\.go$|_generated\.\w+$|^zz_generated|\.min\.js$)",
    )
});
static MIGRATION_FILE: LazyLock<Regex> =
    LazyLock::new(|| js_regex(r"(?i)^\d{3,}(?:[_-]|\.[a-z]+$)"));

/// How far into a file a generated-code banner is looked for, in UTF-16 units.
const HEADER_UNITS: usize = 1024;

/// `Code generated .{0,80}DO NOT EDIT`, `@generated`, `auto-generated`, `autogenerated` and
/// `This file was automatically generated` in the first kilobyte, in any ASCII letter case.
fn has_generated_header(text: &str) -> bool {
    let head = answer_format::utf16::prefix(text, HEADER_UNITS).to_ascii_lowercase();
    if [
        "@generated",
        "auto-generated",
        "autogenerated",
        "this file was automatically generated",
    ]
    .iter()
    .any(|banner| head.contains(banner))
    {
        return true;
    }
    let mut search_from = 0;
    while let Some(found) = head
        .get(search_from..)
        .and_then(|rest| rest.find("code generated "))
    {
        let after = search_from + found + "code generated ".len();
        if banner_closes_within_window(head.get(after..).unwrap_or("")) {
            return true;
        }
        search_from = after;
    }
    false
}

/// Whether `do not edit` follows within eighty UTF-16 units on the same line.
fn banner_closes_within_window(rest: &str) -> bool {
    let mut offset = 0;
    let mut units = 0usize;
    loop {
        let Some(tail) = rest.get(offset..) else {
            return false;
        };
        if tail.starts_with("do not edit") {
            return true;
        }
        let Some(character) = tail.chars().next() else {
            return false;
        };
        units += character.len_utf16();
        if is_line_terminator(character) || units > 80 {
            return false;
        }
        offset += character.len_utf8();
    }
}

fn is_line_terminator(character: char) -> bool {
    matches!(character, '\n' | '\r' | '\u{2028}' | '\u{2029}')
}

fn holds(folders: &[String], names: &[&str]) -> bool {
    folders
        .iter()
        .any(|folder| names.contains(&folder.as_str()))
}

/// One file's class from its path alone, or from its first bytes when the name is silent.
pub fn class_of(path: &str, text: &str) -> SourceClass {
    let mut parts: Vec<&str> = path.split('/').collect();
    let name = parts.pop().unwrap_or("");
    let folders: Vec<String> = parts.iter().map(|part| part.to_lowercase()).collect();
    if holds(&folders, &VENDORED) {
        return SourceClass::Vendored;
    }
    if GENERATED_FILE.is_match(name) || has_generated_header(text) {
        return SourceClass::Generated;
    }
    if holds(&folders, &TESTS) || holds(&folders, &MORE_TESTS) || TEST_FILE.is_match(name) {
        return SourceClass::Test;
    }
    if folders
        .last()
        .is_some_and(|last| MIGRATION_FOLDERS.contains(&last.as_str()))
        && MIGRATION_FILE.is_match(name)
    {
        return SourceClass::Migration;
    }
    if holds(&folders, &BENCHMARKS) || BENCH_FILE.is_match(name) {
        return SourceClass::Benchmark;
    }
    if holds(&folders, &EXAMPLES) {
        return SourceClass::Example;
    }
    if let Some(top) = folders.first() {
        if DOCS.contains(&top.as_str()) {
            return SourceClass::Docs;
        }
        if TOOLING.contains(&top.as_str()) {
            return SourceClass::Tooling;
        }
    } else if ROOT_TOOLING_CONFIG.is_match(name) {
        return SourceClass::Tooling;
    }
    SourceClass::Product
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_path_alone_names_most_classes() {
        for (path, class) in [
            ("src/order/place.ts", SourceClass::Product),
            ("vendor/lib/a.go", SourceClass::Vendored),
            ("src/__tests__/a.ts", SourceClass::Test),
            ("src/a.test.tsx", SourceClass::Test),
            ("src/order_test.go", SourceClass::Test),
            ("db/migrations/0001_initial.py", SourceClass::Migration),
            ("src/db/migrations/helpers.py", SourceClass::Product),
            ("bench/run.rs", SourceClass::Benchmark),
            ("src/sort_bench.rs", SourceClass::Benchmark),
            ("examples/basic/main.go", SourceClass::Example),
            ("docs/conf.py", SourceClass::Docs),
            ("scripts/release.py", SourceClass::Tooling),
            ("vite.config.ts", SourceClass::Tooling),
            ("src/vite.config.ts", SourceClass::Product),
            ("api/user.pb.go", SourceClass::Generated),
            ("web/app.min.js", SourceClass::Generated),
        ] {
            assert_eq!(class_of(path, ""), class, "{path}");
        }
    }

    #[test]
    fn a_generated_banner_in_the_first_kilobyte_makes_a_file_generated() {
        assert_eq!(
            class_of(
                "src/a.go",
                "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a"
            ),
            SourceClass::Generated
        );
        assert_eq!(
            class_of("src/a.ts", "// This file was automatically generated\n"),
            SourceClass::Generated
        );
        assert_eq!(
            class_of("src/a.go", "// Code generated by hand over a long note that runs past the window of eighty characters before it says DO NOT EDIT"),
            SourceClass::Product,
            "the banner's words must fall within eighty characters of its start"
        );
        assert_eq!(
            class_of("src/a.go", "// code\n// generated by x DO NOT EDIT"),
            SourceClass::Product
        );
    }

    #[test]
    fn a_banner_after_the_first_kilobyte_is_not_read() {
        let text = format!("{}\n// @generated", "x".repeat(1100));
        assert_eq!(class_of("src/a.ts", &text), SourceClass::Product);
    }
}
