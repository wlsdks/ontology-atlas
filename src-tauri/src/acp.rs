//! ACP harness — a layer to invoke coding agents already installed by the user within the app.
//!
//! This file's responsibility is **finding**: which executors are actually present on this
//! machine, and what absolute paths are needed to launch them. Protocol (JSON-RPC) parsing
//! does not happen here — the UI layer handles that.
//!
//! ## Why reconstruct PATH directly (measured 2026-08-16)
//!
//! Just because `which node` works in the terminal doesn't mean the **app** can find it.
//! Apps launched via Finder·Dock on macOS do not go through shell initialization files (`.zshrc`, etc.),
//! so the paths set by version managers are entirely missing. Actual measurement on this machine:
//!
//! ```text
//! node · npx · codex → /Users/<me>/.nvm/versions/node/v24.16.0/bin/
//! claude            → /Users/<me>/.local/bin/
//! ```
//!
//! Both are outside the default PATH for GUI apps. So saying "not found" would be a lie,
//! and the user would see a screen stating the tool they just used in the terminal is unavailable.
//!
//! **We do not launch a shell to extract PATH.** Running a login shell executes the user's
//! entire shell configuration, meaning we wouldn't know what gets executed. Instead, we only search **known locations** — exactly what is searched is written in the code, and that list
//! is itself the inspection target.
//!
//! ## Why pin the npx version
//!
//! The adapters (`claude-agent-acp` · `codex-acp`) are separate programs from the CLI. To avoid asking the user
//! to run `npm i -g`, we have two options — either the app bundles its own Node runtime and adapter
//! (reference products take this path, costing 1.06GB), or we invoke `npx` with the existing Node.
//! We chose the latter but **pin the version**: if not pinned, the adapter might update one day,
//! causing the app to silently speak a different protocol.
//!
//! If already installed, use it as-is — npx is slow on first execution.

use std::ffi::{OsStr, OsString};
use std::path::{Path, PathBuf};

/// One item from the committed ACP registry snapshot.
///
/// The canonical list is `src-tauri/src/acp-registry.json`, generated by
/// `scripts/build-acp-registry.mjs`. **Never fetched at runtime** —
/// hitting a CDN every time the app starts is communication the user never asked for, and
/// the list would be empty on a flight.
#[derive(Debug, Clone, serde::Deserialize)]
pub(crate) struct RegistryAgent {
    pub id: String,
    pub name: String,
    pub description: String,
    pub website: Option<String>,
    pub license: Option<String>,
    /// Whether we have **actually verified** it. A marker to prevent
    /// claiming the UI has done something it hasn't.
    pub verified: bool,
    /// The executable name of the real CLI wrapped by that adapter. `None` if unknown —
    /// guessing and filling in would fabricate reasons for UI absence.
    pub cli: Option<String>,
    /// Path to the bundled icon (`/acp-icons/<id>.svg`). Downloaded at build time so the app
    /// does not need to fetch images.
    pub icon: Option<String>,
    /// The vendor's brand color (`#RRGGBB`). Registry icons are all monochrome, so
    /// colors are added separately by the build script. Only **human-verified pairs** have values;
    /// if missing, the UI draws in grayscale — wrong brand color is worse than grayscale.
    #[serde(default, rename = "brandInk")]
    pub brand_ink: Option<String>,
    pub launch: RegistryLaunch,
}

#[derive(Debug, Clone, serde::Deserialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub(crate) enum RegistryLaunch {
    /// `npx -y <package> <args…>`
    Npx {
        package: String,
        #[serde(default)]
        args: Vec<String>,
    },
    /// `uvx <package> <args…>`
    Uvx {
        package: String,
        #[serde(default)]
        args: Vec<String>,
    },
    /// An executable already installed by the user.
    ///
    /// ⚠️ **This comment used to say "the app never fetches it"** — conditionally changed on 2026-08-20
    /// (owner (88)). Installation only happens when all four conditions are met:
    /// the user clicks · we show what will be executed first · it installs only in an app-specific location · the version is pinned. The conditions and rationale are in `.claude/rules/forbidden.md`
    /// under the "Installing agent tools on behalf of the user" section.
    ///
    /// This branch (`Binary`) itself is unrelated to that — this is for **launching what is already in PATH**.
    Binary {
        command: String,
        #[serde(default)]
        args: Vec<String>,
    },
}

#[derive(Debug, Clone, serde::Deserialize)]
struct RegistrySnapshot {
    agents: Vec<RegistryAgent>,
}

/// The snapshot baked into the build. If the file is corrupted, **the build (not runtime)** must fail,
/// so we parse it only once here; if parsing fails, we leave an empty list — an empty list means
/// the UI says "nothing found" rather than launching something invalid.
fn registry() -> &'static [RegistryAgent] {
    static REGISTRY: std::sync::OnceLock<Vec<RegistryAgent>> = std::sync::OnceLock::new();
    REGISTRY.get_or_init(|| {
        serde_json::from_str::<RegistrySnapshot>(include_str!("acp-registry.json"))
            .map(|s| s.agents)
            .unwrap_or_default()
    })
}

pub(crate) fn registry_agent(id: &str) -> Option<&'static RegistryAgent> {
    registry().iter().find(|a| a.id == id)
}

/// How to isolate settings — **only executors we have actually verified** are here.
///
/// Isolation requires knowing different environment variables and credential files per executor; filling
/// them in by guesswork causes login to silently break. So this table grows from
/// actual measurement, not the registry.
#[derive(Debug, Clone, Copy)]
pub(crate) struct IsolationSpec {
    pub id: &'static str,
    /// The environment variable that decides where this executor reads its configuration from.
    pub config_env: &'static str,
    /// The credential file name inside that config directory. To avoid breaking login upon isolation,
    /// we **link** this file to the user's original (do not copy).
    pub credentials_file: &'static str,
    /// The user's original config directory (relative to home).
    pub user_config_dir: &'static str,
}

